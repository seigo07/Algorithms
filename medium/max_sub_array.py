
# 整数配列から、連続する部分配列の最大合計を求める

# Kadaneアルゴリズム: 配列を左から走査し、各要素で「前の合計に足す」か「ここから新しく始める」かを選び、最大値を更新

# 1. 最初の要素を「現在の合計」と「最大の合計」に設定する。
# 2. 次の要素から順番に、以下を繰り返す。
# - 現在の合計：「前の合計＋今の数」と「今の数だけ」の大きい方を選ぶ。
# - 最大の合計：「現在の合計」と「これまでの最大の合計」の大きい方に更新する。
# 3. 最後に「最大の合計」を返す。

# 時間計算量: O(n)
# 空間計算量: O(1)


def max_sub_array(nums):
    current = best = nums[0]
    for num in nums[1:]:
        current = max(num, current + num)   # 「前の合計＋今の数」と「今の数だけ」の大きい方を選ぶ
        best = max(best, current)   # 「現在の合計」と「これまでの最大の合計」の大きい方に更新
    return best


nums = [1, -3, 4, -1, 2, 1, -5, 3]
print(max_sub_array(nums))
